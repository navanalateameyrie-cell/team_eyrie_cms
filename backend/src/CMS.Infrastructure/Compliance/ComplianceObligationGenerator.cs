using CMS.Domain.Entities;
using CMS.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace CMS.Infrastructure.Compliance;

/// <summary>
/// Rolls future compliance obligations forward for every active service file whose service has a
/// cadence configured. Idempotent: re-running against the same horizon never duplicates a (file,
/// period) pair thanks to the DB unique index.
/// </summary>
public interface IComplianceObligationGenerator
{
    Task<GenerationResult> GenerateAsync(DateOnly today, int horizonMonths, Guid? actorUserId, string? actorUserName,
                                          CancellationToken ct = default);
}

public record GenerationResult(int FilesScanned, int ObligationsCreated, int ObligationsSkippedExisting);

public class ComplianceObligationGenerator : IComplianceObligationGenerator
{
    private readonly CmsDbContext _db;
    private readonly ILogger<ComplianceObligationGenerator> _log;

    public ComplianceObligationGenerator(CmsDbContext db, ILogger<ComplianceObligationGenerator> log)
    {
        _db = db;
        _log = log;
    }

    public async Task<GenerationResult> GenerateAsync(DateOnly today, int horizonMonths,
                                                       Guid? actorUserId, string? actorUserName,
                                                       CancellationToken ct = default)
    {
        if (horizonMonths <= 0 || horizonMonths > 36)
            throw new ArgumentOutOfRangeException(nameof(horizonMonths), "Horizon must be 1..36 months");

        // Only services with a cadence drive generation.
        var services = await _db.ServiceDefinitions.AsNoTracking()
            .Where(s => s.IsActive && s.Frequency != null && s.DueDayOffsetDays != null)
            .ToListAsync(ct);
        if (services.Count == 0) return new GenerationResult(0, 0, 0);
        var svcMap = services.ToDictionary(s => s.Id);

        var files = await _db.ServiceFiles
            .Where(f => svcMap.Keys.Contains(f.ServiceDefinitionId)
                        && f.Status != ServiceFileStatus.Closed)
            .ToListAsync(ct);
        if (files.Count == 0) return new GenerationResult(0, 0, 0);

        // Pre-load existing (file, period) keys so we don't ask the DB per candidate.
        var fileIds = files.Select(f => f.Id).ToArray();
        var existingKeys = await _db.ComplianceObligations.AsNoTracking()
            .Where(o => fileIds.Contains(o.ServiceFileId))
            .Select(o => new { o.ServiceFileId, o.PeriodKey })
            .ToListAsync(ct);
        var existingSet = existingKeys
            .GroupBy(x => x.ServiceFileId)
            .ToDictionary(g => g.Key, g => g.Select(x => x.PeriodKey).ToHashSet(StringComparer.OrdinalIgnoreCase));

        var horizonEnd = today.AddMonths(horizonMonths);
        var newObligations = new List<ComplianceObligation>();
        var newEvents = new List<ObligationEvent>();
        int skipped = 0;

        foreach (var file in files)
        {
            var svc = svcMap[file.ServiceDefinitionId];
            var periods = BuildPeriodsUntilDueBy(svc.Frequency!.Value, svc.DueDayOffsetDays!.Value,
                                                  today, horizonEnd, file.OpenedOn);
            if (!existingSet.TryGetValue(file.Id, out var seen))
                seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            foreach (var p in periods)
            {
                if (seen.Contains(p.PeriodKey)) { skipped++; continue; }
                var obligation = new ComplianceObligation(file.Id, p.PeriodKey, p.Start, p.End, p.Due);
                newObligations.Add(obligation);
                newEvents.Add(new ObligationEvent(obligation.Id, ObligationEventKind.Generated,
                    fromStatus: null, toStatus: ComplianceStatus.Pending,
                    staffId: null, note: $"Auto-generated by scheduler ({svc.Frequency})",
                    actorUserId: actorUserId, actorUserName: actorUserName));
                seen.Add(p.PeriodKey);
            }
        }

        if (newObligations.Count > 0)
        {
            _db.ComplianceObligations.AddRange(newObligations);
            _db.ObligationEvents.AddRange(newEvents);
            await _db.SaveChangesAsync(ct);
            _log.LogInformation("Compliance generator: created {N} new obligations across {Files} files",
                newObligations.Count, files.Count);
        }

        return new GenerationResult(files.Count, newObligations.Count, skipped);
    }

    private record Period(string PeriodKey, DateOnly Start, DateOnly End, DateOnly Due);

    /// <summary>
    /// Enumerates all periods whose due date falls between <paramref name="today"/> (inclusive) and
    /// <paramref name="horizonEnd"/> (exclusive). Periods are back-filled from the service file's open
    /// date too — any period whose due date is still in the horizon window AND after the file opened
    /// is generated so that overdue items appear on dashboards even for recently-opened files.
    /// </summary>
    private static IEnumerable<Period> BuildPeriodsUntilDueBy(ComplianceFrequency freq, int offsetDays,
                                                              DateOnly today, DateOnly horizonEnd,
                                                              DateOnly openedOn)
    {
        // We iterate starting a few periods before "today" to make sure overdue items catch up.
        // Hard-stop upper bound: horizonEnd. Lower bound: openedOn OR today-6mo (whichever is later).
        var floor = openedOn > today.AddMonths(-6) ? openedOn : today.AddMonths(-6);
        var startAnchor = AnchorPeriodStart(freq, floor);

        var cursor = startAnchor;
        while (true)
        {
            var (periodKey, periodStart, periodEnd) = DescribePeriod(freq, cursor);
            var due = periodEnd.AddDays(offsetDays);
            if (due >= horizonEnd) yield break;
            if (periodStart < openedOn) { cursor = AdvancePeriod(freq, cursor); continue; }
            yield return new Period(periodKey, periodStart, periodEnd, due);
            cursor = AdvancePeriod(freq, cursor);
        }
    }

    /// <summary>Snap a date backward to the first day of the period that contains it.</summary>
    private static DateOnly AnchorPeriodStart(ComplianceFrequency freq, DateOnly d) => freq switch
    {
        ComplianceFrequency.Monthly => new DateOnly(d.Year, d.Month, 1),
        ComplianceFrequency.Quarterly => QuarterStart(d),
        ComplianceFrequency.HalfYearly => HalfYearStart(d),
        ComplianceFrequency.Annual => FinancialYearStart(d),
        _ => throw new ArgumentOutOfRangeException(nameof(freq))
    };

    private static DateOnly AdvancePeriod(ComplianceFrequency freq, DateOnly periodStart) => freq switch
    {
        ComplianceFrequency.Monthly => periodStart.AddMonths(1),
        ComplianceFrequency.Quarterly => periodStart.AddMonths(3),
        ComplianceFrequency.HalfYearly => periodStart.AddMonths(6),
        ComplianceFrequency.Annual => periodStart.AddYears(1),
        _ => throw new ArgumentOutOfRangeException(nameof(freq))
    };

    private static (string Key, DateOnly Start, DateOnly End) DescribePeriod(ComplianceFrequency freq, DateOnly start)
    {
        switch (freq)
        {
            case ComplianceFrequency.Monthly:
            {
                var end = start.AddMonths(1).AddDays(-1);
                return ($"{start.Year:0000}-{start.Month:00}", start, end);
            }
            case ComplianceFrequency.Quarterly:
            {
                var end = start.AddMonths(3).AddDays(-1);
                // Quarter number 1..4 within Indian FY (Apr-Jun=Q1 … Jan-Mar=Q4)
                var q = ((start.Month - 4 + 12) % 12) / 3 + 1;
                var fy = start.Month >= 4 ? start.Year : start.Year - 1;
                return ($"FY{fy:0000}-Q{q}", start, end);
            }
            case ComplianceFrequency.HalfYearly:
            {
                var end = start.AddMonths(6).AddDays(-1);
                var fy = start.Month >= 4 ? start.Year : start.Year - 1;
                var h = (start.Month is >= 4 and <= 9) ? 1 : 2;
                return ($"FY{fy:0000}-H{h}", start, end);
            }
            case ComplianceFrequency.Annual:
            {
                var end = start.AddYears(1).AddDays(-1);
                return ($"FY{start.Year:0000}", start, end);
            }
            default: throw new ArgumentOutOfRangeException(nameof(freq));
        }
    }

    private static DateOnly QuarterStart(DateOnly d)
    {
        var month = d.Month;
        int qStartMonth = month switch
        {
            >= 4 and <= 6 => 4,
            >= 7 and <= 9 => 7,
            >= 10 and <= 12 => 10,
            _ => 1, // Jan-Mar → Q4 of previous FY
        };
        return new DateOnly(d.Year, qStartMonth, 1);
    }

    private static DateOnly HalfYearStart(DateOnly d) =>
        d.Month is >= 4 and <= 9 ? new DateOnly(d.Year, 4, 1) :
        d.Month >= 10 ? new DateOnly(d.Year, 10, 1) :
        new DateOnly(d.Year - 1, 10, 1);

    private static DateOnly FinancialYearStart(DateOnly d) =>
        d.Month >= 4 ? new DateOnly(d.Year, 4, 1) : new DateOnly(d.Year - 1, 4, 1);
}
